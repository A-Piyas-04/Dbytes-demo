export type Key = keyof typeof S;

export const tr = (lang: Lang, key: Key) => S[key][lang === 'en' ? 0 : 1];
export const tx = (lang: Lang, v: L | undefined) => (v == null ? '' : typeof v === 'string' ? v : v[lang]);

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
export const digits = (lang: Lang, s: string | number) =>
  lang === 'bn' ? String(s).replace(/[0-9]/g, (d) => BN_DIGITS[+d]) : String(s);

export const compact = (lang: Lang, n: number) => {
  let s: string;
  if (n >= 1_000_000) s = (n / 1_000_000).toFixed(n >= 10_000_000 ? 0 : 1).replace(/\.0$/, '') + 'M';
  else if (n >= 1000) s = (n / 1000).toFixed(n >= 100_000 ? 0 : 1).replace(/\.0$/, '') + 'K';
  else s = String(n);
  return digits(lang, s);
};

export const duration = (lang: Lang, mins: number) => {
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  const out = h ? `${h}${tr(lang, 'hoursShort')} ${m ? `${m}${tr(lang, 'min')}` : ''}` : `${m} ${tr(lang, 'min')}`;
  return digits(lang, out.trim());
};

export const clock = (lang: Lang, secs: number) =>
  digits(lang, `${Math.floor(secs / 60)}:${String(Math.floor(secs % 60)).padStart(2, '0')}`);
